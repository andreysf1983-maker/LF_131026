<#
.SYNOPSIS
  Generate SQL seeds for legion_quest_item_target from P05 audit (StartItem + kill objective).

.USAGE
  .\tools\generate_p05_sql.ps1
  .\tools\generate_p05_sql.ps1 -LevelMax 110   # Legion leveling band only
#>
param(
    [int]$LevelMax = 999,
    [string]$Root = "",
    [string]$MysqlExe = "",
    [string]$CnfPath = ""
)

$ErrorActionPreference = "Stop"
if (-not $Root) { $Root = Split-Path $PSScriptRoot -Parent }
if (-not $CnfPath) { $CnfPath = Join-Path $Root "setup_tmp\mysql.cnf" }
if (-not $MysqlExe) {
    $findScript = Join-Path $Root "find_mysql.ps1"
    if (Test-Path $findScript) { $MysqlExe = & $findScript -Port 3306 }
}

function Test-CreditBunnyName([string]$Name) {
    if ([string]::IsNullOrWhiteSpace($Name)) { return $false }
    return $Name -match 'Credit|Bunny|Trigger|Dummy|Stalker|Invisible|Proxy|Spirit Servant|Target|Fire Bunny|\[DNT\]|\[PH\]'
}

$sql = @"
SELECT qt.ID, qt.StartItem, qo.ObjectID, IFNULL(ct.name,''), IFNULL(ct.unit_flags,0),
  EXISTS(SELECT 1 FROM creature c WHERE c.id = qo.ObjectID) AS has_spawn
FROM quest_template qt
JOIN quest_objectives qo ON qo.QuestID = qt.ID AND qo.Type = 0
LEFT JOIN creature_template ct ON ct.entry = qo.ObjectID
WHERE qt.StartItem > 0 AND qt.QuestLevel BETWEEN 1 AND $LevelMax
ORDER BY qt.ID, qo.ObjectID
"@

$raw = & $MysqlExe --defaults-extra-file=$CnfPath world -N -B -e $sql 2>&1
if ($LASTEXITCODE -ne 0) { throw ($raw -join "`n") }

$manualKeys = @{}
try {
    $manualRaw = & $MysqlExe --defaults-extra-file=$CnfPath world -N -B -e `
        "SELECT creature_entry, quest_id FROM legion_quest_item_target WHERE spell_id > 0" 2>&1
    if ($LASTEXITCODE -eq 0) {
        foreach ($line in $manualRaw) {
            if ([string]::IsNullOrWhiteSpace($line)) { continue }
            $p = $line -split "`t"
            if ($p.Count -ge 2) { $manualKeys["$($p[0])|$($p[1])"] = $true }
        }
    }
} catch {
    Write-Host "  [--] legion_quest_item_target not found yet (apply sql/18 first)"
}

$outSql = Join-Path $Root "sql\generated_p05_item_targets.sql"
$genDir = Split-Path $outSql -Parent
New-Item -ItemType Directory -Force -Path $genDir | Out-Null

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("-- AUTO-GENERATED by tools/generate_p05_sql.ps1")
[void]$sb.AppendLine("-- Levels 1-$LevelMax | spell_id 0 = any spell while player holds item")
[void]$sb.AppendLine("-- Skips: credit bunnies, no world spawn, manual spell_id rows in legion_quest_item_target")
[void]$sb.AppendLine("")

$entries = @{}
$skippedCredit = 0
$skippedSpawn = 0
$skippedManual = 0
foreach ($line in $raw) {
    if ([string]::IsNullOrWhiteSpace($line)) { continue }
    $p = $line -split "`t"
    if ($p.Count -lt 6) { continue }
    $questId = [int]$p[0]
    $itemId = [int]$p[1]
    $creature = [int]$p[2]
    $name = $p[3]
    $unitFlags = [int]$p[4]
    $hasSpawn = [int]$p[5] -gt 0
    if ($creature -le 0) { continue }

    $key = "$creature|$questId"
    if ($entries.ContainsKey($key)) { continue }
    if ($manualKeys.ContainsKey($key)) { $skippedManual++; continue }
    if (Test-CreditBunnyName $name) { $skippedCredit++; continue }
    if ($unitFlags -band 33554432) { $skippedCredit++; continue }
    if (-not $hasSpawn) { $skippedSpawn++; continue }

    $entries[$key] = @{ QuestId = $questId; ItemId = $itemId; Creature = $creature; Name = $name }
}

foreach ($kv in ($entries.Values | Sort-Object QuestId, Creature)) {
    $follow = 0
    $despawn = 3000
    if ($kv.Name -match 'Hatchling|Peon|Wounded|Injured') { $follow = 1; $despawn = 60000 }
    [void]$sb.AppendLine(
        "INSERT IGNORE INTO ``legion_quest_item_target`` (creature_entry, spell_id, quest_id, item_id, credit_entry, follow_player, despawn_ms) " +
        "VALUES ($($kv.Creature), 0, $($kv.QuestId), $($kv.ItemId), $($kv.Creature), $follow, $despawn); -- $($kv.Name)"
    )
}

$creatureList = ($entries.Values | ForEach-Object { $_.Creature } | Sort-Object -Unique)
if ($creatureList.Count -gt 0) {
    $inList = ($creatureList -join ",")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("UPDATE ``creature_template`` SET ``AIName`` = '', ``ScriptName`` = 'npc_quest_item_target'")
    [void]$sb.AppendLine("WHERE ``entry`` IN ($inList) AND IFNULL(``ScriptName``, '') IN ('', 'SmartAI');")
}

[System.IO.File]::WriteAllText($outSql, $sb.ToString())
Write-Host "[OK] $($entries.Count) P05 rows -> $outSql"
Write-Host "     skipped credit-bunny=$skippedCredit no-spawn=$skippedSpawn manual=$skippedManual"
Write-Host "[!] Hand-tuned spell rows (sql/18) are preserved; apply sql/18 before generated file."
